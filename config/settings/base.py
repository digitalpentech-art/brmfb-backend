# Compatibility fix for Python 3.13+ where copy.copy(super()) fails in Django BaseContext.__copy__
try:
    from django.template.context import BaseContext
    if not getattr(BaseContext, "_python_313_copy_fixed", False):
        def _fixed_base_context_copy(self):
            duplicate = object.__new__(self.__class__)
            duplicate.__dict__.update(self.__dict__)
            duplicate.dicts = self.dicts[:]
            return duplicate
        BaseContext.__copy__ = _fixed_base_context_copy
        BaseContext._python_313_copy_fixed = True
except Exception:
    pass

